  await page.evaluate(()=>document.querySelectorAll('.view').forEach(e=>e.scrollTop=0));
  assert.ok(await page.$$eval('.group',els=>els.every(e=>{
    const h=e.querySelector('h1'),p=e.querySelector('.frontier-passage p');
    return [h,p].every(n=>{if(!n||!n.textContent.trim())return false;const r=n.getBoundingClientRect();return r.width>100&&r.height>0&&r.right>0&&r.left<innerWidth&&r.bottom>47&&r.top<innerHeight-27;});
  })),'both compact editor headings and source passages intersect viewport');
