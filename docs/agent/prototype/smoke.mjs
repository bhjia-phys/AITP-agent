  assert.ok(requests.every(r=>r.url.startsWith(origin)||r.url.startsWith('data:')),'external request');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed,errors,requests:requests.length,screenshots},null,2));
